"""Checks to run before every push. Exit code 0 only if all checks pass.

1. Tracked files contain no data files: no gz, zip, parquet, npy, pickle,
   joblib or similar, and CSV files only in docs/ (codebook) and
   results/aggregate/.
2. The commit history shows only the expected author identity and no
   attribution trailers, generator notes or links in commit messages.
   Commits by other contributors are accepted only if they touch nothing
   outside their own folder (``OTHER_PATHS``).
3. No tracked file contains per-station or per-row data: no station name
   from the ISMN station list and no OpenSAR patch identifier appears in any
   tracked file, and no tracked CSV has a station, patch or time column.

Files under ``OTHER_PATHS`` belong to another contributor and are not
checked or changed here.

Usage: python tools/prepush_check.py [--data-root PATH]
(``--data-root`` points to the folder with ``data/`` when the check runs in
a separate worktree.)
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
OWNER = "Dania Waseem <i232622@isb.nu.edu.pk>"
OTHER_PATHS = ("BR_Baseline_implementation/",)
BANNED_EXT = {".gz", ".zip", ".rar", ".7z", ".parquet", ".feather", ".npy", ".npz", ".pkl",
              ".pickle", ".joblib", ".h5", ".hdf5", ".nc", ".tif", ".tiff", ".mat", ".pt",
              ".pth", ".ckpt"}
ALLOWED_CSV = ("docs/codebook.csv",)
ROW_COLUMNS = {"station_id", "patch_id", "t", "time", "t_ismn", "lat", "lon"}
# Trailers, generator notes and links that commit messages must not contain.
ATTRIBUTION = re.compile(r"co-authored-by|generated with|generated by|https?://|session",
                         re.IGNORECASE)


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                          check=True).stdout


def is_other(path: str) -> bool:
    return path.startswith(OTHER_PATHS)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", default=str(ROOT))
    data_root = Path(ap.parse_args().data_root)

    files = [f for f in git("ls-files").splitlines() if f and not is_other(f)]
    problems = []

    # 1. Data files (own files only).
    for f in files:
        ext = Path(f).suffix.lower()
        if ext in BANNED_EXT:
            problems.append(f"data file type tracked: {f}")
        if ext == ".csv" and not (f in ALLOWED_CSV or f.startswith("results/aggregate/")):
            problems.append(f"CSV outside allowed folders: {f}")

    # 2. History.
    for line in git("log", "--format=%H%x09%an <%ae>%x09%cn <%ce>").splitlines():
        sha, author, committer = line.split("\t")
        msg = git("log", "-1", "--format=%B", sha)
        for m in msg.splitlines():
            if ATTRIBUTION.search(m):
                problems.append(f"attribution-like text in {sha[:7]}: {m.strip()}")
        if author != OWNER:
            touched = [p for p in git("show", "--name-only", "--format=", sha).splitlines() if p]
            outside = [p for p in touched if not is_other(p)]
            if outside:
                problems.append(f"commit {sha[:7]} by {author} touches files outside "
                                f"{OTHER_PATHS}: {outside[:5]}")
        elif committer not in (OWNER, "GitHub <noreply@github.com>"):
            problems.append(f"commit {sha[:7]} has unexpected committer {committer}")

    # 3. Per-station or per-row content (own files only).
    names = set()
    st = data_root / "data" / "raw" / "ismn" / "stations.csv"
    if st.exists():
        names |= set(pd.read_csv(st)["station_id"].astype(str))
    op = data_root / "data" / "processed" / "opensar_rfi_stats.csv"
    if op.exists():
        names |= set(pd.read_csv(op)["patch_id"].astype(str))
    if not names:
        problems.append("station and patch name lists not found (use --data-root)")
    pattern = re.compile(r"(?<![\w-])(" + "|".join(re.escape(n) for n in sorted(
        names, key=len, reverse=True)) + r")(?![\w-])") if names else None
    for f in files:
        p = ROOT / f
        if not p.exists() or p.suffix.lower() in {".png", ".pdf"}:
            continue
        text = p.read_text(encoding="utf-8", errors="ignore")
        if pattern is not None:
            m = pattern.search(text)
            if m:
                problems.append(f"station or patch name '{m.group(0)}' in {f}")
        if p.suffix.lower() == ".csv":
            bad = set(pd.read_csv(p, nrows=0).columns) & ROW_COLUMNS
            if bad:
                problems.append(f"per-row or per-station columns {sorted(bad)} in {f}")

    other = [f for f in git("ls-files").splitlines() if f and is_other(f)]
    print(f"{len(files)} own tracked files checked; {len(other)} files of another "
          f"contributor under {OTHER_PATHS} left unchecked; {len(names)} station and patch "
          f"names searched")
    if problems:
        print("CHECKS FAILED:")
        for p in problems:
            print("  -", p)
        return 1
    print("all pre-push checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
