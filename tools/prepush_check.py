"""Checks to run before every push. Exit code 0 only if all checks pass.

1. Tracked files contain no data files: no gz, zip, parquet, npy, pickle,
   joblib or similar, and CSV files only in docs/ (codebook, notation) and
   results/aggregate/.
2. The commit history shows only the expected author identity and no
   assistant attribution (Co-Authored-By lines, assistant names, session
   links).
3. No tracked file contains per-station or per-row data: no station name
   from the ISMN station list and no OpenSAR patch identifier appears in any
   tracked file, and no tracked CSV has a station, patch or time column.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
BANNED_EXT = {".gz", ".zip", ".parquet", ".feather", ".npy", ".npz", ".pkl", ".pickle",
              ".joblib", ".h5", ".hdf5", ".nc", ".tif", ".tiff"}
ALLOWED_CSV = ("docs/codebook.csv", "docs/notation.csv")
ROW_COLUMNS = {"station_id", "patch_id", "t", "time", "t_ismn", "lat", "lon"}
# Trailers, generator notes and links that commit messages must not contain.
ATTRIBUTION = re.compile(r"co-authored-by|generated with|generated by|https?://|session",
                         re.IGNORECASE)


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                          check=True).stdout


def main() -> int:
    files = [f for f in git("ls-files").splitlines() if f]
    problems = []

    # 1. Data files.
    for f in files:
        ext = Path(f).suffix.lower()
        if ext in BANNED_EXT:
            problems.append(f"data file type tracked: {f}")
        if ext == ".csv" and not (f in ALLOWED_CSV or f.startswith("results/aggregate/")):
            problems.append(f"CSV outside allowed folders: {f}")

    # 2. History.
    log = git("log", "--format=full")
    authors = set(git("log", "--format=%an <%ae>").splitlines())
    committers = set(git("log", "--format=%cn <%ce>").splitlines())
    for line in log.splitlines():
        if ATTRIBUTION.search(line):
            problems.append(f"attribution-like text in history: {line.strip()}")
    expected = {"Dania Waseem <i232622@isb.nu.edu.pk>"}
    if authors - expected:
        problems.append(f"unexpected authors: {sorted(authors - expected)}")
    if committers - expected - {"GitHub <noreply@github.com>"}:
        problems.append(f"unexpected committers: {sorted(committers - expected)}")

    # 3. Per-station or per-row content.
    names = set()
    st = ROOT / "data" / "raw" / "ismn" / "stations.csv"
    if st.exists():
        names |= set(pd.read_csv(st)["station_id"].astype(str))
    op = ROOT / "data" / "processed" / "opensar_rfi_stats.csv"
    if op.exists():
        names |= set(pd.read_csv(op)["patch_id"].astype(str))
    pattern = re.compile(r"(?<![\w-])(" + "|".join(re.escape(n) for n in sorted(names, key=len,
                                                                             reverse=True))
                         + r")(?![\w-])") if names else None
    for f in files:
        p = ROOT / f
        if p.suffix.lower() in {".png", ".pdf"}:
            continue
        text = p.read_text(encoding="utf-8", errors="ignore")
        if pattern is not None:
            m = pattern.search(text)
            if m:
                problems.append(f"station or patch name '{m.group(0)}' in {f}")
        if p.suffix.lower() == ".csv":
            cols = set(pd.read_csv(p, nrows=0).columns)
            bad = cols & ROW_COLUMNS
            if bad:
                problems.append(f"per-row or per-station columns {sorted(bad)} in {f}")

    print(f"{len(files)} tracked files checked; {len(names)} station and patch names searched")
    if problems:
        print("CHECKS FAILED:")
        for p in problems:
            print("  -", p)
        return 1
    print("all pre-push checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
